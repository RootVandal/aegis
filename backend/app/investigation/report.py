"""Generate a Markdown incident report from stored data only.

Event fields are attacker-controlled, so every value taken from an event is
escaped before it is placed in Markdown. Otherwise a crafted command line
could inject links, HTML or formatting when the report is rendered elsewhere.
"""

import re

from app.db.base import utc_now
from app.investigation.timeline import TimelineEntry
from app.models import Incident
from app.models.enums import NoteKind

_MD_SPECIAL = re.compile(r"([\\`*_{}\[\]<>()#+\-.!|~])")

VERDICT_LABELS = {
    "true_positive": "True positive: malicious or unauthorized activity confirmed",
    "benign_activity": "Benign activity: the behavior occurred but was authorized or expected",
    "false_positive": "False positive: the detection misidentified the activity",
    "inconclusive": "Inconclusive: the available evidence does not support a conclusion",
}


def md(text: object) -> str:
    """Escape Markdown/HTML-significant characters and flatten newlines."""
    return _MD_SPECIAL.sub(r"\\\1", str(text)).replace("\r", " ").replace("\n", " ")


def _ts(value: object) -> str:
    return str(value).replace("+00:00", "Z")


def render_report(incident: Incident, timeline: list[TimelineEntry]) -> str:
    lines: list[str] = []
    add = lines.append

    add(f"# Incident #{incident.id}: {md(incident.title)}")
    add("")
    add(f"- **Status:** {incident.status.value}")
    add(f"- **Severity:** {incident.severity.value}")
    add(f"- **Created:** {_ts(incident.created_at)}")
    add(f"- **Last updated:** {_ts(incident.updated_at)}")
    if incident.resolved_at:
        add(f"- **Resolved:** {_ts(incident.resolved_at)}")
    add(f"- **Report generated:** {_ts(utc_now().replace(microsecond=0))}")
    add("")
    add("> Generated by AEGIS from recorded data. Detection alerts are indicators, not proof")
    add("> of compromise. Statements marked *hypothesis* are unverified analyst reasoning.")
    add("")

    add("## Description")
    add("")
    add(md(incident.description) if incident.description else "_No description._")
    add("")

    add("## Final assessment")
    add("")
    if incident.verdict:
        add(f"**Verdict:** {VERDICT_LABELS[incident.verdict.value]}")
        add("")
        add(md(incident.final_assessment or ""))
        add("")
        add("**Resolution summary:** " + md(incident.resolution_summary or ""))
    else:
        add("_No final assessment has been recorded yet._")
    add("")

    add(f"## Alerts ({len(incident.alerts)})")
    add("")
    if incident.alerts:
        add("| Alert | Rule | Severity | Status | Title |")
        add("| --- | --- | --- | --- | --- |")
        for alert in sorted(incident.alerts, key=lambda a: a.id):
            add(
                f"| #{alert.id} | {md(alert.rule_id)} v{alert.rule_version} | "
                f"{alert.severity.value} | {alert.status.value} | {md(alert.title)} |"
            )
    else:
        add("_No alerts linked._")
    add("")

    add(f"## Timeline ({len(timeline)} events)")
    add("")
    if timeline:
        add("| Time (UTC) | Event | Type | Host | User | Rules | Why it is here |")
        add("| --- | --- | --- | --- | --- | --- | --- |")
        for item in timeline:
            event = item.event
            add(
                f"| {_ts(event.timestamp)} | {md(event.event_id)} | {md(event.event_type)} | "
                f"{md(event.hostname or '')} | {md(event.username or '')} | "
                f"{md(', '.join(item.rule_ids))} | "
                f"{md(' / '.join(s.description for s in item.sources))} |"
            )
    else:
        add("_No events._")
    add("")

    add(f"## Documented evidence ({len(incident.evidence)})")
    add("")
    for evidence in incident.evidence:
        add(
            f"- {md(evidence.event.event_id)} ({_ts(evidence.event.timestamp)}): "
            f"{md(evidence.note)}"
        )
    if not incident.evidence:
        add("_No events were explicitly recorded as evidence._")
    add("")

    add("## Analyst notes")
    add("")
    for note in incident.notes:
        label = "Hypothesis (unverified)" if note.kind == NoteKind.HYPOTHESIS else "Note"
        add(f"- **{label}**, {md(note.author)}, {_ts(note.created_at)}: {md(note.body)}")
    if not incident.notes:
        add("_No notes._")
    add("")

    add("## History")
    add("")
    for entry in incident.history:
        add(f"- {_ts(entry.created_at)} {md(entry.author)}: {md(entry.summary)}")
    add("")
    return "\n".join(lines)
