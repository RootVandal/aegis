"""Render the rule catalog (docs/DETECTION_RULES.md) from the rule classes.

The document is generated, not hand-written, so it cannot drift from the
code; a test fails if the committed file is out of date. Regenerate with:

    python -m app.detection.catalog > ../docs/DETECTION_RULES.md
"""

import json
from typing import Any

from app.detection.mitre import ATTACK_VERSION, VERIFIED_ON
from app.detection.registry import RULES
from app.detection.rule import Rule


def _bullets(items: tuple[str, ...], ordered: bool = False) -> str:
    return "\n".join(f"{i}. {item}" if ordered else f"- {item}" for i, item in enumerate(items, 1))


def _rule_section(rule: Rule[Any]) -> str:
    defaults = rule.parse_params({}).model_dump(mode="json")
    schema = rule.params_model.model_json_schema().get("properties", {})
    params = "\n".join(
        f"| `{name}` | `{json.dumps(value)}` | {schema.get(name, {}).get('description', '')} |"
        for name, value in defaults.items()
    )
    mitre = "\n".join(
        f"| [{m.technique.id}]({m.technique.url}) | {m.technique.name} | "
        f"{', '.join(m.technique.tactics)} | {m.relationship} | {m.limitations} |"
        for m in rule.mitre
    )
    changes = "\n".join(f"- v{c.version} ({c.date}): {c.description}" for c in rule.changelog)
    return f"""## {rule.id}: {rule.name}

{rule.description}

**Version** {rule.version} · **Default severity** {rule.severity.value} ·
**Event types** {", ".join(f"`{t}`" for t in rule.event_types)}

**Required fields:** {", ".join(f"`{f}`" for f in rule.required_fields)}

### Logic

{_bullets(rule.logic, ordered=True)}

### Parameters

| Name | Default | Meaning |
| --- | --- | --- |
{params}

### MITRE ATT&CK

| Technique | Name | Tactics | Why | Not covered |
| --- | --- | --- | --- | --- |
{mitre}

### Investigation steps

{_bullets(rule.investigation_steps, ordered=True)}

### Common false positives

{_bullets(rule.false_positives)}

### Known limitations

{_bullets(rule.limitations)}

### What an alert cannot tell you

{_bullets(rule.unknowns)}

### Change history

{changes}
"""


def render_markdown() -> str:
    index = "\n".join(
        f"| [{rule.id}](#{rule.id.lower()}-{rule.name.lower().replace(' ', '-')}) | {rule.name} "
        f"| {rule.severity.value} | {', '.join(m.technique.id for m in rule.mitre) or '—'} |"
        for rule in RULES
    )
    sections = "\n".join(_rule_section(rule) for rule in RULES)
    return f"""# AEGIS Detection Rules

<!-- Generated by `python -m app.detection.catalog`. Do not edit by hand. -->

AEGIS ships {len(RULES)} deterministic rules. Each one is a small Python class in
`backend/app/detection/rules/` with its logic and the documentation below.
The same events and parameters always produce the same findings.

ATT&CK identifiers were verified against attack.mitre.org (content
{ATTACK_VERSION}) on {VERIFIED_ON}. A mapping describes behavior a rule may
detect. It is not evidence that a particular adversary was involved, and no
rule covers every way a technique can be performed.

Rule results on the labeled `detection-lab` dataset are checked by
`backend/tests/detection/test_engine.py`; see that dataset's docstring for
the positive and lookalike cases per rule.

| Rule | Name | Default severity | ATT&CK |
| --- | --- | --- | --- |
{index}

{sections}"""


if __name__ == "__main__":
    print(render_markdown(), end="")
